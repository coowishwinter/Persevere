// Fallback algorithm to deterministically generate a unique poetic quote for any of the 366 days
export function getDailyQuote(dateStr: string): DailyQuote {
  const [year, month, day] = dateStr.split('-').map(Number);
  const date = new Date(year, month - 1, day);
  const startOfYear = new Date(year, 0, 0);
  const diff = date.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24)); // 1 ~ 366

  // Unique index based on day of year
  const index = Math.abs(dayOfYear - 1) % QUOTES_COLLECTION.length;
  const base = QUOTES_COLLECTION[index];

  // Variations for year-round uniqueness
  const dailyBlessings = [
    "今日一页书，一程汗水，皆是明日破土的底蕴。",
    "知而不行，只是未知。每一次躬身践行，心力便坚韧一分。",
    "步履不停，心自泰然。生活中的风雨，自能化作坦途。",
    "不求今日速成，但求日日不辍，静候时间的复利。",
    "每一次细小的打卡，都是向心目中的自己投出的一票。",
    "走得远从近处起步，登得高从低处登攀。步步踏实，无远弗届。",
    "强健的身体是头脑的基石，静心的阅读是智慧的杠杆。",
    "自律不是禁锢，而是通向从容与自由最坚固的桥梁。",
    "运动塑造体魄，读书拓展精神维度，两者相映成辉。",
    "在日常的平凡琐碎中，建立自己的秩序与定力。",
  ];

  return {
    ...base,
    blessing: dailyBlessings[(dayOfYear * 7 + month * 3 + day) % dailyBlessings.length],
  };
}
